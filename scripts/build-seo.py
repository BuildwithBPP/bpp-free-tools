#!/usr/bin/env python3
"""Writes the crawl and share tags for every tool page, plus sitemap.xml and robots.txt.

BASE_URL below is the one place the public host lives. To move the tools to their own
subdomain, change that line and run:  python3 scripts/build-seo.py
Check mode (exit 1 if anything is out of date):  python3 scripts/build-seo.py --check

Each page keeps its own <title>, meta description, og:title and og:description (the copy
lives in the HTML). This script only owns the block between <!-- seo:begin --> and
<!-- seo:end -->: canonical, og:url, og:image, twitter:card and JSON-LD.
"""
import datetime
import html
import json
import pathlib
import re
import subprocess
import sys

BASE_URL = "https://buildwithbpp.github.io/bpp-free-tools/"  # later: "https://tools.buildwithbpp.com/"

ROOT = pathlib.Path(__file__).resolve().parent.parent

ORG = {
    "@type": "Organization",
    "name": "Business Plans Plus",
    "url": "https://www.buildwithbpp.com",
    "description": "Tampa business consultants & AI implementation",
    "telephone": "+1-813-314-7552",
    "email": "info@buildwithbpp.com",
    "address": {"@type": "PostalAddress", "addressLocality": "Tampa", "addressRegion": "FL", "addressCountry": "US"},
}

# slug = folder; name = the tool's name as HubSpot stores it (lm_magnet_name); type = schema.org type.
PAGES = [
    {"slug": "scorecard", "name": "Owner-Dependency Scorecard", "type": "WebApplication"},
    {"slug": "calculator", "name": "Cost of Owner Dependence Calculator", "type": "WebApplication"},
    {"slug": "ai-readiness", "name": "AI Employee Readiness Assessment", "type": "WebApplication"},
    {"slug": "foundation-score", "name": "Foundation Readiness Score", "type": "WebApplication"},
    {"slug": "system-finder", "name": "Business System Finder", "type": "WebApplication"},
    {"slug": "guides", "name": "Run-Without-You Guide", "type": "WebPage"},
]

BEGIN = "<!-- seo:begin (generated by scripts/build-seo.py from BASE_URL; edit the script, not this block) -->"
END = "<!-- seo:end -->"
BLOCK_RE = re.compile(r"<!-- seo:begin.*?<!-- seo:end -->\n", re.S)
ANCHOR_RE = re.compile(r'(<meta name="description" content="[^"]*">\n)')


def meta(src, attr, key):
    m = re.search(r'<meta %s="%s" content="([^"]*)">' % (attr, re.escape(key)), src)
    if not m:
        sys.exit("missing <meta %s=%s>" % (attr, key))
    return html.unescape(m.group(1))


def esc(s):
    return html.escape(s, quote=True)


def block(page, src):
    url = BASE_URL + page["slug"] + "/"
    image = BASE_URL + "assets/og/" + page["slug"] + ".png"
    desc = meta(src, "name", "description")
    ld = {
        "@context": "https://schema.org",
        "@type": page["type"],
        "name": page["name"],
        "headline": meta(src, "property", "og:title"),
        "description": desc,
        "url": url,
        "image": image,
        "inLanguage": "en-US",
        "isAccessibleForFree": True,
        "publisher": ORG,
    }
    if page["type"] == "WebApplication":
        ld.update({
            "applicationCategory": "BusinessApplication",
            "operatingSystem": "Any",
            "browserRequirements": "Requires JavaScript",
            "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
        })
    ld_json = json.dumps(ld, indent=2, ensure_ascii=False).replace("</", "<\\/")
    lines = [
        BEGIN,
        '<link rel="canonical" href="%s">' % esc(url),
        '<meta property="og:url" content="%s">' % esc(url),
        '<meta property="og:site_name" content="Business Plans Plus">',
        '<meta property="og:locale" content="en_US">',
        '<meta property="og:image" content="%s">' % esc(image),
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="627">',
        '<meta property="og:image:alt" content="%s">' % esc(page["name"] + " by Business Plans Plus, Tampa"),
        '<meta name="twitter:card" content="summary_large_image">',
        '<script type="application/ld+json">',
        ld_json,
        "</script>",
        END,
    ]
    return "\n".join(lines) + "\n"


def lastmod(path):
    """Last commit date of the file, or today if it has uncommitted changes."""
    rel = str(path.relative_to(ROOT))
    dirty = subprocess.run(["git", "-C", str(ROOT), "diff", "--quiet", "HEAD", "--", rel]).returncode != 0
    if not dirty:
        out = subprocess.run(["git", "-C", str(ROOT), "log", "-1", "--format=%cs", "--", rel], capture_output=True, text=True).stdout.strip()
        if out:
            return out
    return datetime.date.today().isoformat()


def main():
    check = "--check" in sys.argv
    stale = []
    for page in PAGES:
        path = ROOT / page["slug"] / "index.html"
        src = path.read_text()
        base = BLOCK_RE.sub("", src)
        if not ANCHOR_RE.search(base):
            sys.exit("no meta description to anchor on in " + str(path))
        new = ANCHOR_RE.sub(lambda m: m.group(1) + block(page, base), base, count=1)
        if new != src:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(new)

    urls = "".join(
        "  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n  </url>\n"
        % (esc(BASE_URL + p["slug"] + "/"), lastmod(ROOT / p["slug"] / "index.html"))
        for p in PAGES
    )
    extras = {
        "sitemap.xml": '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + "</urlset>\n",
        "robots.txt": "# Crawlers only read robots.txt at a host root, so this takes effect once the tools\n"
        "# move to their own subdomain (see README). Generated by scripts/build-seo.py.\n"
        "User-agent: *\nAllow: /\n\nSitemap: " + BASE_URL + "sitemap.xml\n",
    }
    for name, body in extras.items():
        path = ROOT / name
        if not path.exists() or path.read_text() != body:
            stale.append(name)
            if not check:
                path.write_text(body)

    if check:
        print("up to date" if not stale else "out of date: " + ", ".join(stale))
        sys.exit(1 if stale else 0)
    print("wrote: " + (", ".join(stale) if stale else "nothing (already up to date)"))


if __name__ == "__main__":
    main()
